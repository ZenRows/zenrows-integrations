// Builds one Activepieces action per endpoint we offer (shared/billing.yaml) from
// the published API spec, each in its own src/lib/actions/<name>.ts, and
// src/lib/actions/generated.ts listing them for index.ts. Fetch has a
// hand-written action (Scrape URL), so it's left out here. npm run render runs it.
const handWritten = ["fetch"];

// "create_batch_job" → "createBatchJobAction" in "create-batch-job.ts"; "Read a job" → "Read A Job"; "job_id" → "Job ID".
const camel = (id) => id.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const file = (id) => id.replaceAll("_", "-");
const header = `// Generated by platforms/activepieces/scripts/render.mjs from the API spec and
// shared/billing.yaml (zenrows-integrations); edit those, not this file.
`;
const titleCase = (text) => text.replace(/(^|[\s(/-])([a-z])/g, (_, before, c) => before + c.toUpperCase());
const words = { id: "ID", url: "URL", urls: "URLs", css: "CSS", js: "JS" };
const label = (name) => name.split("_").map((w) => words[w] ?? w.charAt(0).toUpperCase() + w.slice(1)).join(" ");
const str = (value) => JSON.stringify(value);

// One prop per parameter or body field: its type picks the Property.
const kinds = { integer: "Number", number: "Number", boolean: "Checkbox", object: "Json", array: "Json" };
function prop(name, schema, required) {
  const common = [`displayName: ${str(label(name))}`, ...(schema.description ? [`description: ${str(schema.description)}`] : []), `required: ${required}`];
  if (schema.default !== undefined) common.push(`defaultValue: ${str(schema.default)}`);
  if (schema.enum) {
    const options = schema.enum.map((v) => `{ label: ${str(String(v))}, value: ${str(v)} }`).join(", ");
    return `Property.StaticDropdown({ ${common.join(", ")}, options: { disabled: false, options: [${options}] } })`;
  }
  return `Property.${kinds[schema.type] ?? "ShortText"}({ ${common.join(", ")} })`;
}

export default function render({ apiEndpoints }) {
  const where = "platforms/activepieces/scripts/render.mjs";
  const endpoints = apiEndpoints().filter((e) => !handWritten.includes(e.key));
  const files = {};
  for (const e of endpoints) {
    // The key goes in the X-API-Key header where the operation takes it, else as apikey.
    const inHeader = e.keyIn.header === "X-API-Key";
    if (!inHeader && e.keyIn.query !== "apikey") throw new Error(`${where}: ${e.operation} takes the key neither in X-API-Key nor as apikey`);
    const props = [];
    const operation = { method: e.method, server: e.server, path: e.path, key: inHeader ? "header" : "query" };
    for (const [part, schema] of Object.entries(e.input)) {
      if (schema.type !== "object" || !schema.properties) throw new Error(`${where}: ${e.operation}'s ${part} isn't an object with properties`);
      // Path parameters are filled into the path by name; the client needs the others' names.
      if (part !== "path") operation[part] = Object.keys(schema.properties);
      for (const [name, field] of Object.entries(schema.properties)) {
        if (props.some(([n]) => n === name)) throw new Error(`${where}: ${e.operation} has "${name}" in two places`);
        props.push([name, prop(name, field, (schema.required ?? []).includes(name))]);
      }
    }
    const propsCode = props.length ? `{\n${props.map(([name, p]) => `    ${name}: ${p},\n`).join("")}  }` : "{}";
    files[`src/lib/actions/${file(e.id)}.ts`] = `${header}import { createAction${props.length ? ", Property" : ""} } from '@activepieces/pieces-framework';
import { zenrowsAuth } from '../auth';
import { zenrowsClient } from '../common/client';

export const ${camel(e.id)}Action = createAction({
  auth: zenrowsAuth,
  name: ${str(e.id)},
  displayName: ${str(titleCase(e.name))},
  description: ${str(e.description ?? e.name)},
  props: ${propsCode},
  async run({ auth, propsValue }) {
    return zenrowsClient.callOperation({ apiKey: auth.secret_text, operation: ${str(operation)}, values: propsValue });
  },
});
`;
  }
  files["src/lib/actions/generated.ts"] = `${header}${endpoints.map((e) => `import { ${camel(e.id)}Action } from './${file(e.id)}';\n`).join("")}
export const generatedActions = [${endpoints.map((e) => `${camel(e.id)}Action`).join(", ")}];
`;
  return files;
}
